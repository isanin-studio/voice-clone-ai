"""Нотация ударения: «зам+ок» -> «замо́к».

XTTS-v2 воспринимает комбинирующий акут U+0301, но набирать его
неудобно. Плюс перед ударной гласной конвертируется в акут.
"""
import re

ACUTE = "́"
VOWELS = "аеёиоуыэюяАЕЁИОУЫЭЮЯ"

_MARK = re.compile(rf"\+([{VOWELS}])")


def apply_stress(text: str) -> str:
    """Заменяет «+гласная» на «гласная + акут»."""
    return _MARK.sub(rf"\1{ACUTE}", text)
